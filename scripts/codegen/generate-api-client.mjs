import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const [, , openApiPath, outputPath] = process.argv;

if (!openApiPath || !outputPath) {
  console.error("usage: node scripts/codegen/generate-api-client.mjs <openapi.json> <output.ts>");
  process.exit(1);
}

const schema = JSON.parse(await readFile(openApiPath, "utf8"));
const operations = [];

for (const [path, methods] of Object.entries(schema.paths ?? {})) {
  for (const [method, operation] of Object.entries(methods)) {
    operations.push({
      method: method.toUpperCase(),
      path,
      operationId: operation.operationId ?? `${method}_${path.replace(/[^a-zA-Z0-9]+/g, "_")}`,
      tags: operation.tags ?? []
    });
  }
}

operations.sort((a, b) => a.operationId.localeCompare(b.operationId));

const content = `// This file is generated by scripts/codegen/generate-api-client.mjs.
// Do not edit by hand.

export type HttpMethod = ${[...new Set(operations.map((op) => op.method))]
  .sort()
  .map((method) => JSON.stringify(method))
  .join(" | ")};

export type ApiOperation = {
  method: HttpMethod;
  path: string;
  operationId: string;
  tags: readonly string[];
};

export const operations = ${JSON.stringify(operations, null, 2)} as const satisfies readonly ApiOperation[];

export type ApiClientOptions = {
  baseUrl: string;
  fetchImpl?: typeof fetch;
  headers?: Record<string, string>;
};

export function createApiClient(options: ApiClientOptions) {
  const fetcher = options.fetchImpl ?? fetch;

  return {
    operations,

    async request<T>(method: HttpMethod, path: string, body?: unknown): Promise<T> {
      const response = await fetcher(new URL(path, options.baseUrl), {
        method,
        headers: {
          "content-type": "application/json",
          ...options.headers
        },
        body: body === undefined ? undefined : JSON.stringify(body)
      });

      if (!response.ok) {
        throw await response.json();
      }

      const text = await response.text();
      return (text ? JSON.parse(text) : undefined) as T;
    }
  };
}
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, content);
console.log(`generated ${operations.length} operations -> ${outputPath}`);
